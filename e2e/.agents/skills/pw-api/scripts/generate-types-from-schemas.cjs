const OUTPUT_DIR = path.resolve(ROOT_DIR, "api/ibpm/models/generated");

async function generateAllTypes() {
    if (!fs.existsSync(OUTPUT_DIR)) {
        fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    }

    console.log(`🚀 Starting TypeScript models generation from JSON Schemas...`);
    const indexExports = [];

    for (const item of SCHEMAS_CONFIG) {
        const schemaFilePath = path.resolve(ROOT_DIR, item.file);
        if (!fs.existsSync(schemaFilePath)) {
            console.warn(`⚠️ Schema file not found, skipping: ${item.file}`);
            continue;
        }

        try {
            const rawContent = fs.readFileSync(schemaFilePath, "utf-8");
            const schema = JSON.parse(rawContent);

            // Ensure valid identifier title for top-level interface/type name
            schema.title = item.name;

            const tsCode = await compile(schema, item.name, {
                bannerComment: `/* eslint-disable */\n/**\n * Auto-generated by json-schema-to-typescript from:\n * ${item.file}\n * DO NOT EDIT DIRECTLY.\n */\n`,
                style: {
                    singleQuote: false,
                    semi: true
                },
                unreachableDefinitions: false
            });

            const outputPath = path.resolve(OUTPUT_DIR, item.out);
            fs.writeFileSync(outputPath, tsCode, "utf-8");
            console.log(`✅ Generated: ${item.out} (${(tsCode.length / 1024).toFixed(1)} KB) from ${item.file}`);

            const moduleName = item.out.replace(/\.ts$/, "");
            indexExports.push(`export * from "./${moduleName}";`);
        } catch (error) {
            console.error(`❌ Failed to compile schema ${item.file}:`, error);
        }
    }

    // Write index.ts for convenient grouped imports
    const indexTsPath = path.resolve(OUTPUT_DIR, "index.ts");
    const indexContent = `/* eslint-disable */\n/**\n * Auto-generated index for all schema-derived TypeScript models.\n */\n${indexExports.join("\n")}\n`;
    fs.writeFileSync(indexTsPath, indexContent, "utf-8");
    console.log(`\n🎉 Index generated at api/ibpm/models/generated/index.ts (${indexExports.length} models exported)`);
}

if (require.main === module) {
    generateAllTypes().catch(err => {
        console.error("Fatal error during schema types generation:", err);
        process.exit(1);
    });
}

module.exports = { generateAllTypes };
