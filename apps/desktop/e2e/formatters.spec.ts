import { test, expect } from '@playwright/test';
import {
  formatFeedTitle,
  generateSupplierFeedTitle,
  isAutoGeneratedFeedName,
} from '@/lib/formatters';

test.describe('formatters — formatFeedTitle (short and clean algorithm)', () => {
  test('omits generic boilerplate filename and query parameters, returning clean domain', () => {
    const url =
      'https://livolo.kiev.ua/products_feed.xml?hash_tag=313e3f0e4bd4878fa657c5c5d544b64d&sales_notes=&product_ids=';
    expect(formatFeedTitle(null, url)).toBe('livolo.kiev.ua');
    expect(formatFeedTitle(url)).toBe('livolo.kiev.ua');
  });

  test('strips www. prefix from domain', () => {
    expect(formatFeedTitle('https://www.prom.ua/price_list.xml')).toBe('prom.ua');
  });

  test('cleans legacy formatted strings with generic filenames in parentheses', () => {
    expect(formatFeedTitle('livolo.kiev.ua (products_feed.xml)')).toBe('livolo.kiev.ua');
    expect(formatFeedTitle('livolo.kiev.ua (products_feed)')).toBe('livolo.kiev.ua');
    expect(formatFeedTitle('dropship.ua (catalog.xml)')).toBe('dropship.ua');
  });

  test('preserves specific distinguishing sub-feed names while stripping technical extensions', () => {
    expect(formatFeedTitle('https://supplier.ua/feeds/lighting.xml')).toBe(
      'supplier.ua (lighting)',
    );
    expect(formatFeedTitle('supplier.ua (lighting.xml)')).toBe('supplier.ua (lighting)');
    expect(formatFeedTitle('https://electronics.com/outlet.csv')).toBe('electronics.com (outlet)');
  });

  test('preserves custom human-entered feed titles untouched', () => {
    expect(formatFeedTitle('Офіційний каталог Livolo')).toBe('Офіційний каталог Livolo');
    expect(formatFeedTitle('Основний прайс 2026')).toBe('Основний прайс 2026');
  });

  test('cleans local file uploads', () => {
    expect(formatFeedTitle('products_feed.xml')).toBe('Каталог товарів');
    expect(formatFeedTitle('smart_switches.csv')).toBe('smart_switches');
  });

  test('handles null, undefined, and empty string gracefully', () => {
    expect(formatFeedTitle(null, null)).toBe('');
    expect(formatFeedTitle(undefined, undefined)).toBe('');
    expect(formatFeedTitle('   ')).toBe('');
  });
});

test.describe('formatters — generateSupplierFeedTitle (ultra-short supplier-based naming)', () => {
  test('uses clean supplier name for the first feed', () => {
    expect(generateSupplierFeedTitle('Mobioptom')).toBe('Mobioptom');
    expect(generateSupplierFeedTitle('Mobioptom', 0)).toBe('Mobioptom');
    expect(generateSupplierFeedTitle('Mobioptom', [])).toBe('Mobioptom');
  });

  test('generates Mobioptom_2, Mobioptom_3 when count is provided', () => {
    expect(generateSupplierFeedTitle('Mobioptom', 1)).toBe('Mobioptom_2');
    expect(generateSupplierFeedTitle('Mobioptom', 2)).toBe('Mobioptom_3');
  });

  test('resolves lowest available index when array of existing feeds is provided', () => {
    expect(generateSupplierFeedTitle('Mobioptom', ['Mobioptom'])).toBe('Mobioptom_2');
    expect(
      generateSupplierFeedTitle('Mobioptom', [{ name: 'Mobioptom' }, { name: 'Mobioptom_2' }]),
    ).toBe('Mobioptom_3');
    // If base name is free, uses base name
    expect(generateSupplierFeedTitle('Mobioptom', [{ name: 'Mobioptom_2' }])).toBe('Mobioptom');
  });

  test('falls back to Каталог if supplierName is empty or whitespace', () => {
    expect(generateSupplierFeedTitle('')).toBe('Каталог');
    expect(generateSupplierFeedTitle(null)).toBe('Каталог');
    expect(generateSupplierFeedTitle(null, 1)).toBe('Каталог_2');
    expect(generateSupplierFeedTitle('', ['Каталог'])).toBe('Каталог_2');
  });

  test('identifies auto-generated feed names for safe replacement', () => {
    expect(isAutoGeneratedFeedName('', 'Mobioptom')).toBe(true);
    expect(isAutoGeneratedFeedName('Mobioptom', 'Mobioptom')).toBe(true);
    expect(isAutoGeneratedFeedName('Mobioptom_2', 'Mobioptom')).toBe(true);
    expect(isAutoGeneratedFeedName('Mobioptom_3', 'Mobioptom')).toBe(true);
    expect(isAutoGeneratedFeedName('ExportWebskladCSV.csv', 'Mobioptom')).toBe(true);
    expect(isAutoGeneratedFeedName('products_feed.xml', 'Mobioptom')).toBe(true);
    expect(isAutoGeneratedFeedName('Каталог', 'Mobioptom')).toBe(true);
    expect(isAutoGeneratedFeedName('Каталог товарів', 'Mobioptom')).toBe(true);

    // Custom user-entered names must NOT be treated as auto-generated
    expect(isAutoGeneratedFeedName('Оптовий прайс', 'Mobioptom')).toBe(false);
    expect(isAutoGeneratedFeedName('Розетка Дроп 2026', 'Mobioptom')).toBe(false);
  });
});
